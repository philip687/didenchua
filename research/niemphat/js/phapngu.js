const DAY_MS = 864e5, VN_MS = 7 * 36e5;
// Đổi câu lúc 0 giờ giờ Việt Nam
export const phapToday = (now = Date.now()) => {
  const [verse, text] = PHAP_NGU[Math.floor((now + VN_MS) / DAY_MS) % PHAP_NGU.length];
  return { text, source: `Theo Kinh Pháp Cú, câu ${verse}` };
};
